/**
 * go2rtc Process Manager & WebRTC/MSE Streaming Proxy for VOSCCTV
 * Bridges Dahua NVR RTSP feeds directly to client GPU hardware-accelerated WebRTC.
 */

const { spawn } = require('child_process');
const fs = require('fs');
const httpProxy = require('http-proxy');
const path = require('path');

let go2rtcProcess = null;
const GO2RTC_PORT = 1984;
const GO2RTC_WEBRTC_PORT = 8555;
const CONFIG_PATH = path.join(__dirname, 'go2rtc.yaml');
const BIN_DIR = path.join(__dirname, 'bin');

// Dedicated proxy instance for go2rtc
const go2rtcProxy = httpProxy.createProxyServer({
  target: `http://127.0.0.1:${GO2RTC_PORT}`,
  ws: true
});

go2rtcProxy.on('error', (err, req, res) => {
  if (err.code === 'ECONNRESET' || err.code === 'EPIPE') return;
  console.warn('[go2rtc:proxy] Gateway error:', err.message);
  if (res && res.writeHead && !res.headersSent) {
    res.writeHead(502, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'go2rtc gateway unavailable', details: err.message }));
  }
});

/**
 * Determine the correct go2rtc binary for the current operating system
 */
function getBinaryPath() {
  if (process.platform === 'win32') {
    return path.join(BIN_DIR, 'go2rtc.exe');
  } else if (process.platform === 'linux') {
    const candidate1 = path.join(BIN_DIR, 'go2rtc_linux_amd64');
    const candidate2 = path.join(BIN_DIR, 'go2rtc');
    if (fs.existsSync(candidate1)) return candidate1;
    if (fs.existsSync(candidate2)) return candidate2;
    return candidate1;
  } else if (process.platform === 'darwin') {
    return path.join(BIN_DIR, 'go2rtc_mac');
  }
  return path.join(BIN_DIR, 'go2rtc');
}

/**
 * Generate go2rtc.yaml configuration containing all 64 RTSP channels
 */
function generateGo2rtcConfig(nvrs) {
  let streamsYaml = '';

  for (const nvr of nvrs) {
    const user = encodeURIComponent(nvr.username || 'iot');
    const pass = encodeURIComponent(nvr.password || 'iot12345');
    const ip = nvr.ip;
    const port = nvr.rtspPort || 554;

    for (let ch = 1; ch <= 32; ch++) {
      // Sub Stream (default for multi-channel GPU wall, low bandwidth & near-zero CPU)
      const subUrl = `rtsp://${user}:${pass}@${ip}:${port}/cam/realmonitor?channel=${ch}&subtype=1`;
      // Main Stream (for HD full-screen expansion)
      const mainUrl = `rtsp://${user}:${pass}@${ip}:${port}/cam/realmonitor?channel=${ch}&subtype=0`;

      streamsYaml += `  ${nvr.id}_ch${ch}:\n    - ${subUrl}\n`;
      streamsYaml += `  ${nvr.id}_ch${ch}_hd:\n    - ${mainUrl}\n`;
    }
  }

  const yamlContent = `# Auto-generated by VOSCCTV Dashboard
api:
  listen: "127.0.0.1:${GO2RTC_PORT}"

rtsp:
  listen: ""

webrtc:
  listen: "127.0.0.1:${GO2RTC_WEBRTC_PORT}"

streams:
${streamsYaml}
`;

  fs.writeFileSync(CONFIG_PATH, yamlContent, 'utf8');
  console.log(`[go2rtc] Generated configuration at ${CONFIG_PATH} (64 video streams registered)`);
  return CONFIG_PATH;
}

/**
 * Start go2rtc background process
 */
function startGo2rtc(nvrs) {
  if (go2rtcProcess) {
    console.log('[go2rtc] Process is already running (PID: ' + go2rtcProcess.pid + ')');
    return;
  }

  const binPath = getBinaryPath();
  if (!fs.existsSync(binPath)) {
    console.warn(`[go2rtc] Binary not found at ${binPath}. WebRTC streaming will be unavailable until binary is present.`);
    return;
  }

  // Ensure binary is executable on Linux/Mac
  if (process.platform !== 'win32') {
    try {
      fs.chmodSync(binPath, 0o755);
    } catch (e) {}
  }

  generateGo2rtcConfig(nvrs);

  console.log(`[go2rtc] Spawning ${binPath} with config ${CONFIG_PATH}...`);
  go2rtcProcess = spawn(binPath, ['-config', CONFIG_PATH], {
    cwd: __dirname,
    stdio: ['ignore', 'pipe', 'pipe']
  });

  go2rtcProcess.stdout.on('data', (data) => {
    const msg = data.toString().trim();
    if (msg) console.log(`[go2rtc] ${msg}`);
  });

  go2rtcProcess.stderr.on('data', (data) => {
    const msg = data.toString().trim();
    if (msg) console.warn(`[go2rtc:err] ${msg}`);
  });

  go2rtcProcess.on('exit', (code, signal) => {
    console.log(`[go2rtc] Process exited (code: ${code}, signal: ${signal})`);
    go2rtcProcess = null;
  });

  go2rtcProcess.on('error', (err) => {
    console.error('[go2rtc] Failed to start process:', err.message);
    go2rtcProcess = null;
  });
}

/**
 * Stop go2rtc process
 */
function stopGo2rtc() {
  if (go2rtcProcess) {
    console.log('[go2rtc] Stopping background process...');
    go2rtcProcess.kill('SIGTERM');
    go2rtcProcess = null;
  }
}

/**
 * Setup HTTP & WebSocket proxy routes inside Express and Dashboard HTTP Server
 */
function setupGo2rtcProxy(app, server) {
  // 1. Relay HTTP endpoints (/api/go2rtc/* -> http://127.0.0.1:1984/api/*)
  app.all('/api/go2rtc*', (req, res) => {
    req.url = req.url.replace(/^\/api\/go2rtc/, '/api');
    go2rtcProxy.web(req, res);
  });

  // 2. Handle WebSocket upgrades for MSE or WebRTC data channels (/api/go2rtc/ws)
  server.on('upgrade', (req, socket, head) => {
    if (req.url && (req.url.startsWith('/api/go2rtc') || req.url.startsWith('/api/ws'))) {
      req.url = req.url.replace(/^\/api\/go2rtc/, '/api');
      go2rtcProxy.ws(req, socket, head);
    }
  });
}

// Clean shutdown listeners
process.on('SIGINT', stopGo2rtc);
process.on('SIGTERM', stopGo2rtc);
process.on('exit', stopGo2rtc);

module.exports = {
  startGo2rtc,
  stopGo2rtc,
  setupGo2rtcProxy,
  getBinaryPath
};
