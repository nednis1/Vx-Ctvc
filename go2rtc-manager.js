/**
 * go2rtc Process Manager & WebRTC/MSE Streaming Proxy for VOSCCTV
 * Bridges Dahua NVR RTSP feeds directly to client GPU hardware-accelerated WebRTC.
 */

const { spawn } = require('child_process');
const fs = require('fs');
const httpProxy = require('http-proxy');
const path = require('path');

let go2rtcProcess = null;
let isShuttingDown = false;
let restartTimer = null;
let lastNvrsConfig = null;
const GO2RTC_PORT = 1984;
const GO2RTC_WEBRTC_PORT = 8555;
const CONFIG_PATH = path.join(__dirname, 'go2rtc.yaml');
const BIN_DIR = path.join(__dirname, 'bin');

// Dedicated proxy instance for go2rtc
const go2rtcProxy = httpProxy.createProxyServer({
  target: `http://127.0.0.1:${GO2RTC_PORT}`,
  ws: true
});

go2rtcProxy.on('error', (err, req, res) => {
  if (err.code === 'ECONNRESET' || err.code === 'EPIPE') return;
  console.warn('[go2rtc:proxy] Gateway error:', err.message);
  if (err.code === 'ECONNREFUSED') {
    // Automatically trigger watchdog recovery if port refused
    ensureGo2rtcRunning(lastNvrsConfig).catch(() => {});
  }
  if (res && res.writeHead && !res.headersSent) {
    res.writeHead(502, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'go2rtc gateway unavailable, recovering...', details: err.message }));
  }
});

/**
 * Determine the correct go2rtc binary for the current operating system
 */
function getBinaryPath() {
  if (process.platform === 'win32') {
    return path.join(BIN_DIR, 'go2rtc.exe');
  } else if (process.platform === 'linux') {
    const candidate1 = path.join(BIN_DIR, 'go2rtc_linux_amd64');
    const candidate2 = path.join(BIN_DIR, 'go2rtc');
    if (fs.existsSync(candidate1)) return candidate1;
    if (fs.existsSync(candidate2)) return candidate2;
    return candidate1;
  } else if (process.platform === 'darwin') {
    return path.join(BIN_DIR, 'go2rtc_mac');
  }
  return path.join(BIN_DIR, 'go2rtc');
}

/**
 * Generate go2rtc.yaml configuration containing all 64 RTSP channels
 */
function generateGo2rtcConfig(nvrs) {
  let streamsYaml = '';

  for (const nvr of nvrs) {
    const user = encodeURIComponent(nvr.username || 'iot');
    const pass = encodeURIComponent(nvr.password || 'iot12345');
    const ip = nvr.ip;
    const port = nvr.rtspPort || 554;

    for (let ch = 1; ch <= 32; ch++) {
      // Sub Stream (default for multi-channel GPU wall, low bandwidth & near-zero CPU, fast start with backchannel=0)
      const subUrl = `rtsp://${user}:${pass}@${ip}:${port}/cam/realmonitor?channel=${ch}&subtype=1#backchannel=0`;
      // Main Stream (for HD full-screen expansion)
      const mainUrl = `rtsp://${user}:${pass}@${ip}:${port}/cam/realmonitor?channel=${ch}&subtype=0#backchannel=0`;

      streamsYaml += `  ${nvr.id}_ch${ch}:\n    - ${subUrl}\n`;
      streamsYaml += `  ${nvr.id}_ch${ch}_hd:\n    - ${mainUrl}\n`;
    }
  }

  const yamlContent = `# Auto-generated by VOSCCTV Dashboard
api:
  listen: "127.0.0.1:${GO2RTC_PORT}"

rtsp:
  listen: ""

webrtc:
  listen: ":${GO2RTC_WEBRTC_PORT}"

streams:
${streamsYaml}
`;

  fs.writeFileSync(CONFIG_PATH, yamlContent, 'utf8');
  console.log(`[go2rtc] Generated configuration at ${CONFIG_PATH} (64 video streams registered)`);
  return CONFIG_PATH;
}

/**
 * Terminate any orphaned zombie go2rtc processes (e.g. from previous unclean shutdowns on Windows)
 */
function killZombieGo2rtc() {
  if (process.platform === 'win32') {
    try {
      const { execSync } = require('child_process');
      execSync('taskkill /F /IM go2rtc.exe 2>nul', { stdio: 'ignore' });
    } catch (e) {}
  }
}

/**
 * Check if go2rtc API is healthy and answering on port 1984
 */
function checkGo2rtcHealthy() {
  return new Promise((resolve) => {
    const http = require('http');
    const req = http.get(`http://127.0.0.1:${GO2RTC_PORT}/api/streams`, { timeout: 800 }, (res) => {
      res.resume();
      resolve(res.statusCode === 200);
    });
    req.on('error', () => resolve(false));
    req.on('timeout', () => {
      req.destroy();
      resolve(false);
    });
  });
}

/**
 * Ensure go2rtc is actively running and accepting connections on port 1984
 */
async function ensureGo2rtcRunning(nvrs) {
  if (nvrs && Array.isArray(nvrs) && nvrs.length > 0) {
    lastNvrsConfig = nvrs;
  }

  // 1. If already healthy and responding, return immediately
  const isHealthy = await checkGo2rtcHealthy();
  if (isHealthy) return true;

  console.log(`[go2rtc] Gateway not responding on port ${GO2RTC_PORT}. Ensuring process is running...`);
  startGo2rtc(lastNvrsConfig);

  // 2. Poll until gateway is ready (up to 3 seconds)
  const maxAttempts = 15;
  for (let i = 0; i < maxAttempts; i++) {
    await new Promise(r => setTimeout(r, 200));
    const healthyNow = await checkGo2rtcHealthy();
    if (healthyNow) {
      console.log(`[go2rtc] Gateway is now healthy and accepting connections on port ${GO2RTC_PORT}.`);
      return true;
    }
  }

  console.warn(`[go2rtc] Gateway failed to respond within 3000ms on port ${GO2RTC_PORT}.`);
  return false;
}

/**
 * Start go2rtc background process
 */
function startGo2rtc(nvrs) {
  if (nvrs && Array.isArray(nvrs) && nvrs.length > 0) {
    lastNvrsConfig = nvrs;
  }

  if (go2rtcProcess) {
    try {
      // Check if process is still alive
      if (process.kill(go2rtcProcess.pid, 0)) {
        return;
      }
    } catch (e) {
      go2rtcProcess = null;
    }
  }

  const binPath = getBinaryPath();
  if (!fs.existsSync(binPath)) {
    console.warn(`[go2rtc] Binary not found at ${binPath}. WebRTC streaming will be unavailable until binary is present.`);
    return;
  }

  // Ensure binary is executable on Linux/Mac
  if (process.platform !== 'win32') {
    try {
      fs.chmodSync(binPath, 0o755);
    } catch (e) {}
  }

  // Free ports 1984 & 8555 by killing any orphaned zombie go2rtc processes
  killZombieGo2rtc();

  if (lastNvrsConfig) {
    generateGo2rtcConfig(lastNvrsConfig);
  }

  isShuttingDown = false;
  console.log(`[go2rtc] Spawning ${binPath} with config ${CONFIG_PATH}...`);
  go2rtcProcess = spawn(binPath, ['-config', CONFIG_PATH], {
    cwd: __dirname,
    stdio: ['ignore', 'pipe', 'pipe']
  });

  go2rtcProcess.stdout.on('data', (data) => {
    const msg = data.toString().trim();
    if (msg) console.log(`[go2rtc] ${msg}`);
  });

  go2rtcProcess.stderr.on('data', (data) => {
    const msg = data.toString().trim();
    if (msg) console.warn(`[go2rtc:err] ${msg}`);
  });

  go2rtcProcess.on('exit', (code, signal) => {
    console.warn(`[go2rtc] Process exited (code: ${code}, signal: ${signal})`);
    go2rtcProcess = null;
    if (!isShuttingDown) {
      console.log('[go2rtc] Unexpected exit detected. Watchdog auto-restarting in 1s...');
      if (restartTimer) clearTimeout(restartTimer);
      restartTimer = setTimeout(() => {
        if (!isShuttingDown && !go2rtcProcess) {
          startGo2rtc(lastNvrsConfig);
        }
      }, 1000);
    }
  });

  go2rtcProcess.on('error', (err) => {
    console.error('[go2rtc] Failed to start process:', err.message);
    go2rtcProcess = null;
  });
}

/**
 * Stop go2rtc process
 */
function stopGo2rtc() {
  isShuttingDown = true;
  if (restartTimer) {
    clearTimeout(restartTimer);
    restartTimer = null;
  }
  if (go2rtcProcess) {
    console.log('[go2rtc] Stopping background process...');
    try {
      go2rtcProcess.kill('SIGTERM');
    } catch (e) {}
    go2rtcProcess = null;
  }
  killZombieGo2rtc();
}

/**
 * Setup HTTP & WebSocket proxy routes inside Express and Dashboard HTTP Server
 */
function setupGo2rtcProxy(app, server, authCheckFn) {
  // 1. Relay HTTP endpoints (/api/go2rtc/* -> http://127.0.0.1:1984/api/*)
  app.all('/api/go2rtc*', (req, res) => {
    if (typeof authCheckFn === 'function' && !authCheckFn(req)) {
      return res.status(401).json({ error: 'Unauthorized: Authentication required' });
    }
    req.url = req.url.replace(/^\/api\/go2rtc/, '/api');
    go2rtcProxy.web(req, res);
  });

  // 2. Handle WebSocket upgrades for MSE or WebRTC data channels (/api/go2rtc/ws)
  server.on('upgrade', (req, socket, head) => {
    if (req.url && (req.url.startsWith('/api/go2rtc') || req.url.startsWith('/api/ws'))) {
      if (typeof authCheckFn === 'function' && !authCheckFn(req)) {
        socket.write('HTTP/1.1 401 Unauthorized\r\n\r\n');
        socket.destroy();
        return;
      }
      req.url = req.url.replace(/^\/api\/go2rtc/, '/api');
      go2rtcProxy.ws(req, socket, head);
    }
  });
}

// Clean shutdown listeners
process.on('SIGINT', stopGo2rtc);
process.on('SIGTERM', stopGo2rtc);
process.on('exit', stopGo2rtc);

module.exports = {
  GO2RTC_PORT,
  GO2RTC_WEBRTC_PORT,
  startGo2rtc,
  stopGo2rtc,
  ensureGo2rtcRunning,
  checkGo2rtcHealthy,
  setupGo2rtcProxy,
  getBinaryPath
};
